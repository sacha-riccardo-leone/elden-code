// Hand-drawn heroes speak with their own voice (by hero id); Maren wears the knight.
export const VOICES = {
  tarnished, knight: maren, bloodbender: vael, bandit, fortuna, ronin, runelord, paladin, ysolde,
  champion: twofold, queen: twofold, 'twofold-dawn': twofold, 'twofold-dusk': twofold,
};

// Generic Tarnished who go by one of these names speak with that voice instead of the common one.
const BY_NAME = { Ysolde: 'ysolde' };

export function voiceOf(npc) {
  return VOICES[npc.hero?.hero] || VOICES[BY_NAME[npc.name?.first]] || tarnished;
}

// Where someone calls home: their session's island, or the Round Table for a hero no session has
// taken up (and for Maren).
export function homeOf(npc) {
  return npc.session?.project || 'the Round Table';
}

const recent = new Map(); // voice -> its last few lines, so nobody repeats themselves too soon

function pick(voice, intent) {
  const own = voice.all || voice.lines[intent] || voice.lines[intent.split('_')[0]];
  const options = own || tarnished.lines[intent] || ['…'];
  const used = recent.get(voice) || [];
  const fresh = options.filter((o) => !used.includes(o));
  const pool = fresh.length ? fresh : options;
  const line = pool[Math.floor(Math.random() * pool.length)];
  used.push(line);
  if (used.length > 12) used.shift();
  recent.set(voice, used);
  return line;
}

function fill(line, ctx) {
  return line.replace(/\{(\w+)\}/g, (_, k) => String(ctx[k] ?? ''));
}

// `npc` says `intent` in its own voice, to `to` (another Tarnished, Maren, or no one). `extra`
// fills further blanks ({n} for the news lines).
export function speak(npc, intent, to = null, extra = {}) {
  const n = extra.n;
  const ctx = { name: to?.name?.first || 'friend', project: homeOf(npc), otherProject: to ? homeOf(to) : '', s: n === 1 ? '' : 's', ...extra };
  const text = fill(pick(voiceOf(npc), intent), ctx);
  // "the Round Table is quiet" opens a sentence: capitalise it
  return text.replace(/^[a-z]/, (c) => c.toUpperCase());
}
